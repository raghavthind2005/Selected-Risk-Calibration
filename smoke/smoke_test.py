#!/usr/bin/env python3
"""Smoke test: rebuild every table and figure and compare against the committed ones.

Everything it compares against lives in THIS repository -- `tables/` and
`figures/` as committed. It never reaches outside the repo.

Steps:
  1. build a fresh virtual environment from requirements.txt
     (skip with --no-venv to use the current interpreter);
  2. run run_all.sh twice, and require the two runs to agree byte for
     byte -- including the PDFs, which are deterministic because
     analysis/_figsave.py writes them without a CreationDate;
  3. compare every rebuilt artefact against the committed copy, byte for byte;
  4. verify MANIFEST.sha256 over the whole repository.

Exit code 0 only if every step passes.

usage: python3 smoke/smoke_test.py [--no-venv] [--keep]
"""
from __future__ import annotations
import argparse, hashlib, os, pathlib, shutil, subprocess, sys, tempfile, time

REPO = pathlib.Path(__file__).resolve().parent.parent
REQ = REPO / "requirements.txt"
OUT_DIRS = ("tables", "figures")

# Not in MANIFEST.sha256, and deliberately so: both are written *after* the
# manifest is computed, so neither can contain its own hash.
MANIFEST_EXEMPT = {"MANIFEST.sha256"}
# Regenerated by run_all.sh, and not committed.
EXEMPT_DIRS = ("derived", "rerun", ".git")


def sha(p: pathlib.Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def snapshot() -> dict:
    out = {}
    for d in OUT_DIRS:
        for p in sorted((REPO / d).rglob("*")):
            if p.is_file():
                out[str(p.relative_to(REPO))] = sha(p)
    return out


def run(cmd, **kw):
    r = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if r.returncode != 0:
        sys.stderr.write((r.stdout or "")[-4000:] + (r.stderr or "")[-4000:])
    return r


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-venv", action="store_true",
                    help="use the current interpreter instead of building a venv")
    ap.add_argument("--keep", action="store_true", help="keep the temporary venv")
    args = ap.parse_args()

    print("=" * 74)
    print("Level 1 smoke test")
    print("=" * 74)
    failures: list[str] = []

    # ---- committed state, recorded before anything runs ----
    committed = snapshot()
    print(f"\n[0] committed artefacts: {len(committed)} files under {', '.join(OUT_DIRS)}/")

    # ---- [1] environment ----
    tmp = None
    if args.no_venv:
        py = sys.executable
        print(f"\n[1] using the current interpreter (--no-venv): {py}")
    else:
        tmp = pathlib.Path(tempfile.mkdtemp(prefix="src_smoke_"))
        print(f"\n[1] fresh virtual environment from {REQ.relative_to(REPO)}")
        t0 = time.time()
        r = run([sys.executable, "-m", "venv", str(tmp / "venv")])
        if r.returncode != 0:
            print("    FAIL: could not create the venv"); return 1
        py = str(tmp / "venv" / "bin" / "python")
        r = run([py, "-m", "pip", "install", "-q", "-r", str(REQ)])
        print(f"    pip install rc={r.returncode} in {time.time()-t0:.0f}s")
        if r.returncode != 0:
            failures.append("pip install failed")
    ver = run([py, "-c",
               "import sys,numpy,scipy,matplotlib;"
               "print(sys.version.split()[0],numpy.__version__,scipy.__version__,matplotlib.__version__)"])
    print(f"    interpreter: {ver.stdout.strip()}")

    # ---- [2] run twice, require determinism ----
    print("\n[2] run_all.sh, twice")
    env = dict(os.environ, PYTHON=py)
    t0 = time.time()
    r = run(["bash", "run_all.sh"], cwd=REPO, env=env)
    if r.returncode != 0:
        print("    FAIL: first run failed"); return 1
    first = snapshot()
    t1 = time.time()
    print(f"    run 1: {t1-t0:.1f}s")
    r = run(["bash", "run_all.sh"], cwd=REPO, env=env)
    if r.returncode != 0:
        print("    FAIL: second run failed"); return 1
    second = snapshot()
    print(f"    run 2: {time.time()-t1:.1f}s")
    unstable = sorted(k for k in first if first[k] != second.get(k))
    if unstable:
        failures.append(f"{len(unstable)} artefact(s) differ between two runs")
        for k in unstable:
            print(f"    UNSTABLE between runs: {k}")
    else:
        print(f"    run 1 vs run 2 byte-identical: {len(first)}/{len(first)}")

    # ---- [3] against the committed copies IN THIS REPO ----
    print("\n[3] rebuilt vs committed (this repository's tables/ and figures/)")
    tables_bad, figures_bad = [], []
    for k in sorted(committed):
        got = second.get(k)
        if got == committed[k]:
            continue
        (tables_bad if k.startswith("tables/") else figures_bad).append(k)
    for k in sorted(set(second) - set(committed)):
        print(f"    NEW (not committed): {k}")
    if tables_bad:
        failures.append(f"{len(tables_bad)} table(s) differ from committed")
        for k in tables_bad: print(f"    DIFFERS: {k}")
    if figures_bad:
        failures.append(f"{len(figures_bad)} figure(s) differ from committed")
        for k in figures_bad: print(f"    DIFFERS: {k}")
    n_tab = sum(1 for k in committed if k.startswith("tables/"))
    n_fig = sum(1 for k in committed if k.startswith("figures/"))
    print(f"    tables : {n_tab - len(tables_bad)}/{n_tab} byte-identical")
    print(f"    figures: {n_fig - len(figures_bad)}/{n_fig} byte-identical")
    print("    figure tolerance: byte-for-byte, both PNG and PDF. PDFs are")
    print("    deterministic because analysis/_figsave.py pins CreationDate;")
    print("    PNGs reproduce byte-for-byte only at the pinned matplotlib version.")

    # ---- [4] manifest ----
    print("\n[4] MANIFEST.sha256 over the whole repository")
    man = REPO / "MANIFEST.sha256"
    bad = missing = checked = 0
    for line in man.read_text().splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        digest, rel = line.split("  ", 1)
        p = REPO / rel
        checked += 1
        if not p.is_file():
            missing += 1
            print(f"    MISSING: {rel}")
        elif sha(p) != digest:
            bad += 1
            print(f"    FAILED : {rel}")
    print(f"    {checked - bad - missing}/{checked} entries verified"
          f" ({bad} mismatched, {missing} missing)")
    if bad or missing:
        failures.append(f"manifest: {bad} mismatched, {missing} missing")
    # and nothing untracked by the manifest
    listed = {l.split("  ", 1)[1] for l in man.read_text().splitlines()
              if l.strip() and not l.lstrip().startswith("#")}
    on_disk = {str(p.relative_to(REPO)) for p in REPO.rglob("*")
               if p.is_file() and str(p.relative_to(REPO)) not in MANIFEST_EXEMPT
               and not any(d in p.relative_to(REPO).parts for d in EXEMPT_DIRS)
               and "__pycache__" not in p.parts and p.suffix not in (".pyc", ".pyo")
               and p.name != ".DS_Store"}
    extra = sorted(on_disk - listed)
    if extra:
        failures.append(f"{len(extra)} file(s) on disk are not in the manifest")
        for k in extra[:20]:
            print(f"    NOT IN MANIFEST: {k}")

    if tmp and not args.keep:
        shutil.rmtree(tmp, ignore_errors=True)

    print("\n" + "=" * 74)
    if failures:
        print("SMOKE TEST: FAIL")
        for f in failures:
            print(f"  - {f}")
    else:
        print("SMOKE TEST: PASS")
    print("=" * 74)
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
